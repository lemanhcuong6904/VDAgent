CREATE TABLE dw.fact_unit_price_history (
    price_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    unit_key BIGINT NOT NULL REFERENCES dw.dim_unit_master(unit_key),
    effective_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    old_asking_price_vnd BIGINT NOT NULL,
    new_asking_price_vnd BIGINT NOT NULL,
    price_change_pct DECIMAL(5,2) NOT NULL,
    change_reason VARCHAR(64)
);

CREATE TABLE dw.fact_sales_funnel_daily (
    funnel_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    unit_key BIGINT NOT NULL REFERENCES dw.dim_unit_master(unit_key),
    web_listing_views INTEGER NOT NULL,
    inquiry_leads_count SMALLINT NOT NULL,
    site_visits_count SMALLINT NOT NULL,
    booking_reservations SMALLINT NOT NULL,
    booking_cancellations SMALLINT NOT NULL,
    cancellation_reason VARCHAR(64)
);

CREATE TABLE dw.fact_unit_inventory_snapshot (
    snapshot_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    unit_key BIGINT NOT NULL REFERENCES dw.dim_unit_master(unit_key),
    project_key INTEGER NOT NULL REFERENCES dw.dim_project_profile(project_key),
    zone_key INTEGER NOT NULL REFERENCES dw.dim_zone_master(zone_key),
    channel_key INTEGER NOT NULL REFERENCES dw.dim_sales_channel(channel_key),
    launch_batch_id VARCHAR(32) NOT NULL,
    release_date DATE NOT NULL,
    inventory_status VARCHAR(16) NOT NULL,
    sold_date DATE,
    unsold_days_dom INTEGER NOT NULL,
    is_overdue_flag BOOLEAN NOT NULL,
    asking_price_vnd BIGINT NOT NULL,
    discount_pct DECIMAL(5,2) NOT NULL,
    concession_value_vnd BIGINT NOT NULL,
    net_price_vnd BIGINT NOT NULL,
    asking_price_per_m2 BIGINT NOT NULL,
    net_price_per_m2 BIGINT NOT NULL,
    subsidy_duration_mo SMALLINT NOT NULL,
    principal_grace_mo SMALLINT NOT NULL,
    base_commission_pct DECIMAL(4,2) NOT NULL,
    spiff_bonus_vnd BIGINT,
    is_exclusive_lock BOOLEAN NOT NULL,
