CREATE TABLE dw.dm_unit_friction_diagnostics (
    diagnostic_id VARCHAR(64) NOT NULL PRIMARY KEY,
    snapshot_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    unit_key BIGINT NOT NULL REFERENCES dw.dim_unit_master(unit_key),
    unit_code VARCHAR(32) NOT NULL,
    project_name VARCHAR(128) NOT NULL,
    zone_name VARCHAR(64) NOT NULL,
    unsold_days_dom INTEGER NOT NULL,
    price_spread_vs_peer_pct DECIMAL(5,2),
    ticket_size_vs_income_ratio DECIMAL(4,1),
    physical_defect_penalty SMALLINT NOT NULL,
    thermal_view_penalty SMALLINT NOT NULL,
    secondary_price_gap_pct DECIMAL(5,2),
    funnel_dropoff_rate_pct DECIMAL(5,2),
    primary_cause_code VARCHAR(32) NOT NULL,
    recommended_action VARCHAR(64) NOT NULL
);

CREATE TABLE dw.unit_diagnostic_causes (
    diagnostic_id VARCHAR(64) NOT NULL REFERENCES dw.dm_unit_friction_diagnostics(diagnostic_id),
    cause_code VARCHAR(32) NOT NULL,
    unit_key BIGINT NOT NULL REFERENCES dw.dim_unit_master(unit_key),
    snapshot_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
